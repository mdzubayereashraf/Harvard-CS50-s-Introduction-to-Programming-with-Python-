#While loops staring from 0 and will run until the condition is false.
#  In this case, it will print "Meao" 5 times.

i = 0

while i < 5 :
    print("Meao")
    i += 1

#while loop staring from 15 and will run until the condition is false.
i = 15
while i > 0:
    print("Meao")
    i -= 1 # i = i - 1